//! Ephemeral session identity.
//!
//! Each GhostChat session generates a fresh Ed25519 key pair and a
//! `BasicCredential` backed by 32 random bytes.  Nothing here is persisted;
//! the identity is dropped at session end.
//!
//! VERIFIED FROM LOCAL SOURCE (openmls_basic_credential-0.6.0/src/lib.rs):
//!   - `SignatureKeyPair::new(scheme) -> Result<Self, CryptoError>`
//!   - `SignatureKeyPair::store(storage) -> Result<(), E>`
//!   - `SignatureKeyPair::public() -> &[u8]`
//!
//! VERIFIED FROM LOCAL SOURCE (openmls-0.9.0/src/credentials/mod.rs):
//!   - `BasicCredential` and `CredentialWithKey` live in `openmls::credentials`
//!     (re-exported via `openmls::prelude::*`).

use openmls::prelude::BasicCredential;
use openmls::prelude::{Ciphersuite, CredentialWithKey, KeyPackage, OpenMlsProvider};
use openmls_basic_credential::SignatureKeyPair;
use openmls_rust_crypto::OpenMlsRustCrypto;
use zeroize::Zeroize;

use crate::core::{GhostChatError, ParticipantId, Result};

/// An ephemeral session identity comprising an Ed25519 signing key and a
/// one-time `BasicCredential`.
///
/// The signing key is stored in `MemoryStorage` so that openmls can retrieve
/// it during group operations; it is never written to disk.
pub struct EphemeralIdentity {
    /// The raw Ed25519 key pair.  Retained so callers can pass `&signer` to
    /// openmls operations.
    pub signer: SignatureKeyPair,
    /// The openmls credential bundle (public key + credential type).
    pub credential_with_key: CredentialWithKey,
    /// The random BasicCredential identity bytes. These remain in memory and
    /// are never included in an application-facing response.
    identity_bytes: Vec<u8>,
}

impl Drop for EphemeralIdentity {
    fn drop(&mut self) {
        self.identity_bytes.zeroize();
    }
}

impl EphemeralIdentity {
    /// Generate a fresh identity for `ciphersuite` and register the signing
    /// key in `provider.storage()`.
    ///
    /// `rand::random` is used only to produce the 32-byte opaque identity
    /// blob that appears in the `BasicCredential`; it is not used for any
    /// cryptographic key material (the key pair is generated by
    /// `SignatureKeyPair::new` which calls the OS CSPRNG internally).
    pub fn generate(ciphersuite: Ciphersuite, provider: &OpenMlsRustCrypto) -> Result<Self> {
        // Generate key pair — uses OS CSPRNG internally via OsRng.
        let signer = SignatureKeyPair::new(ciphersuite.signature_algorithm())
            .map_err(|e| GhostChatError::CryptoError(e.to_string()))?;

        // Store in the provider's in-memory key store so openmls can look it
        // up during Commit/application-message signing.
        signer
            .store(provider.storage())
            .map_err(|e| GhostChatError::StorageError(e.to_string()))?;

        // Build an opaque 32-byte identity (not personally identifying).
        let identity_bytes: [u8; 32] = rand::random();
        let credential = BasicCredential::new(identity_bytes.to_vec());

        let credential_with_key = CredentialWithKey {
            credential: credential.into(),
            signature_key: signer.public().into(),
        };

        Ok(Self {
            signer,
            credential_with_key,
            identity_bytes: identity_bytes.to_vec(),
        })
    }

    /// Return the opaque credential identity bytes for internal protocol use.
    pub fn identity_bytes(&self) -> &[u8] {
        &self.identity_bytes
    }

    /// Return the ephemeral public signing key.
    pub fn public_key(&self) -> &[u8] {
        self.signer.public()
    }

    /// Return a non-identifying routing identifier derived from the public key.
    pub fn participant_id(&self) -> ParticipantId {
        ParticipantId::from_public_key(self.signer.public())
    }

    /// Build and register a KeyPackage for this identity.
    ///
    /// The returned package is public. OpenMLS stores the matching private
    /// key material in the supplied provider's in-memory storage.
    pub fn key_package(
        &self,
        ciphersuite: Ciphersuite,
        provider: &OpenMlsRustCrypto,
    ) -> Result<KeyPackage> {
        KeyPackage::builder()
            .build(
                ciphersuite,
                provider,
                &self.signer,
                self.credential_with_key.clone(),
            )
            .map(|bundle| bundle.key_package().clone())
            .map_err(|e| GhostChatError::MlsError(e.to_string()))
    }
}

// ─── Tests ────────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;
    use openmls::prelude::Ciphersuite;

    fn default_ciphersuite() -> Ciphersuite {
        Ciphersuite::MLS_128_DHKEMX25519_CHACHA20POLY1305_SHA256_Ed25519
    }

    #[test]
    fn generate_returns_identity() {
        let provider = OpenMlsRustCrypto::default();
        let identity = EphemeralIdentity::generate(default_ciphersuite(), &provider)
            .expect("identity generation should succeed");

        // Public key must be non-empty.
        assert!(!identity.signer.public().is_empty());
    }

    #[test]
    fn two_generated_identities_have_different_public_keys() {
        let provider = OpenMlsRustCrypto::default();
        let a = EphemeralIdentity::generate(default_ciphersuite(), &provider).unwrap();
        let b = EphemeralIdentity::generate(default_ciphersuite(), &provider).unwrap();
        assert_ne!(a.signer.public(), b.signer.public());
    }
}
